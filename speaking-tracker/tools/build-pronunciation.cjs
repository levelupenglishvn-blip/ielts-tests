/* Canonical data lives in data/pronunciation-taxonomy.json. No dependencies. */
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/pronunciation-taxonomy.json'), 'utf8'));
const ids = new Set();
for (const item of data.catalog) {
  if (!item.id || !item.label || ids.has(item.id)) throw Error('Invalid/duplicate issue ID: ' + item.id);
  ids.add(item.id);
}
const terms = new Set();
for (const m of data.mappings) {
  if (terms.has(m.term) || m.issueIds.length > 4 || m.issueIds.some(id => !ids.has(id))) throw Error('Invalid mapping: ' + m.term);
  terms.add(m.term);
}
const json = JSON.stringify(data, null, 2);
const outputs = {
  'data/pronunciation-taxonomy.js': '/* Generated by tools/build-pronunciation.cjs; do not edit. */\nwindow.LU.PRONUNCIATION_DATA = ' + json + ';\n',
  'backend/PronunciationData.gs': '/* Generated by tools/build-pronunciation.cjs; do not edit. */\nconst PN_DATA = ' + json + ';\n'
};
for (const [file, text] of Object.entries(outputs)) {
  const dest = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(dest, 'utf8') !== text) throw Error('Generated data is stale: ' + file);
  } else fs.writeFileSync(dest, text);
}
console.log('Pronunciation data: ' + ids.size + ' labels, ' + terms.size + ' mappings.');
